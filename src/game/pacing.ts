/**
 * Облегчённый режим для слабой видеокарты (встроенная в ноутбук).
 *
 * Нейросети MediaPipe считают на той же видеокарте, что рисует игру. Замер на AMD Radeon 660M (экран 144 Гц):
 * рука сама по себе — 7 мс, а рядом с игрой — 33 мс: распознавание стоит в очереди за кадрами игры,
 * которые идут со скоростью экрана и со сглаживанием MSAA ×4. Главный поток ждёт его — кадры игры рвутся.
 *
 * Поэтому, если распознавание устойчиво медленное, игра (1) сглаживает края через SMAA вместо MSAA ×4 —
 * на глаз то же, а видеокарте на треть меньше работы, и (2) на экране 120 Гц и выше рисует каждый второй
 * кадр экрана (~72 к/с) — у видеокарты появляются паузы, в которые нейросети успевают. На сильной видеокарте
 * распознавание быстрое, и ничего не меняется. Включился — до перезагрузки не выключается, чтобы картинка не мигала.
 */

/** Распознавание медленнее этого (мс на кадр камеры) — на экране 144 Гц это больше двух кадров экрана. */
export const SLOW_INFER_MS = 14
/** Сколько последних замеров смотрим (раз в 250 мс — 3 с) и какая их доля должна быть медленной. */
export const SLOW_WINDOW = 12
export const SLOW_SHARE = 0.75
/** К какой частоте кадров тянемся на быстром экране: 144 Гц → каждый 2-й кадр, 240 Гц → каждый 3-й. */
export const TARGET_RENDER_FPS = 72

/** Через сколько кадров экрана рисовать: на 60–100 Гц — каждый, на 120–165 Гц — каждый второй. */
export function framesPerRender(refreshHz: number) {
  if (!(refreshHz > 0)) return 1
  return Math.max(1, Math.round(refreshHz / TARGET_RENDER_FPS))
}

/** Частота экрана по интервалам между кадрами (мс). Медиана: кадры, задержанные нейросетью, её не сбивают. */
export function refreshRate(intervals: number[]) {
  if (intervals.length < 10) return 0
  const sorted = [...intervals].sort((a, b) => a - b)
  const mid = sorted[sorted.length >> 1]
  return mid > 0 ? 1000 / mid : 0
}

/** Распознавание медленное: из последних SLOW_WINDOW замеров почти все дольше порога. */
export function isTrackingSlow(samples: number[]) {
  if (samples.length < SLOW_WINDOW) return false
  const slow = samples.slice(-SLOW_WINDOW).filter((ms) => ms > SLOW_INFER_MS).length
  return slow >= SLOW_WINDOW * SLOW_SHARE
}
