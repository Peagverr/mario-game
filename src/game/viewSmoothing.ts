/**
 * Сглаживание поворота мира левым кулаком.
 *
 * Трекер меняет угол только с частотой камеры (≈60 Гц), а экран рисует чаще (до 165 Гц) и неровно:
 * без сглаживания в части кадров мир стоит, в части прыгает — глаз видит это как «оп, лагнуло».
 * Камера мягко догоняет угол руки (экспоненциально, время ROTATE_SMOOTH_S): шаг за кадр пропорционален
 * длительности кадра — скорость поворота ровная, а один кривой кадр трекера не дёргает мир.
 */

/** Время, за которое мир догоняет руку на ~63%. Больше — плавнее, но мир отстаёт от руки. */
export const ROTATE_SMOOTH_S = 0.06

/** Значение `cur`, сдвинутое к `target` за кадр длиной `dt` секунд. Не проскакивает цель при любом dt. */
export function follow(cur: number, target: number, dt: number, tau: number) {
  return cur + (target - cur) * (1 - Math.exp(-Math.max(0, dt) / tau))
}
